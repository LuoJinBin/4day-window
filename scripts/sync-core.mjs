// 从 public/assets 的浏览器源码生成 src/core/logic.js（Node 可导入的纯逻辑模块）。
// 原则：不改写任何业务代码，只做「拼接 + 导出」。页面逻辑仍以 public/assets/app.js 为准。
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PARTS = ['app-core.js', 'app-backtest.js', 'app-charts.js', 'app-runtime.js'];
const partPaths = PARTS.map((f) => path.join(root, 'public/assets', f));
const dataPath = path.join(root, 'public/assets/snapshot-data.js');
const outPath = path.join(root, 'src/core/logic.js');

const app = partPaths.map((p) => fs.readFileSync(p, 'utf8')).join('\n');
const data = fs.readFileSync(dataPath, 'utf8').trim();

// boot() 是最后一个顶层函数；之后的监听器/首屏渲染属于浏览器启动代码，不进核心模块。
const bootStart = app.indexOf('async function boot()');
if (bootStart < 0) throw new Error('未找到 boot()，public/assets 结构可能已变化');

let i = app.indexOf('{', bootStart);
let depth = 0;
let quote = null;
let escaped = false;

while (i < app.length) {
  const ch = app[i];
  const next = app[i + 1];

  if (quote) {
    if (escaped) escaped = false;
    else if (ch === '\\') escaped = true;
    else if (quote === '`' && ch === '$' && next === '{') {
      let d = 0;
      let j = i + 1;
      while (j < app.length) {
        if (app[j] === '{') d += 1;
        else if (app[j] === '}') {
          d -= 1;
          if (d === 0) break;
        }
        j += 1;
      }
      i = j + 1;
      continue;
    } else if (ch === quote) quote = null;
    i += 1;
    continue;
  }

  if (ch === '"' || ch === "'" || ch === '`') { quote = ch; i += 1; continue; }
  if (ch === '/' && next === '/') { i = app.indexOf('\n', i); continue; }
  if (ch === '/' && next === '*') { i = app.indexOf('*/', i) + 2; continue; }
  if (ch === '{') depth += 1;
  else if (ch === '}') {
    depth -= 1;
    if (depth === 0) { i += 1; break; }
  }
  i += 1;
}

const coreBody = app.slice(0, i);

const EXPORTS = [
  'median', 'forecastMeta', 'chinaParts', 'chinaIso', 'chinaHour', 'leadOf', 'applyObservedDay', 'completedHourlyRain',
  'dayScore', 'metrics', 'buildWindows', 'packDays',
  'riskOf', 'riskText', 'wxWord', 'confTier', 'confWhy',
  'winPen', 'verdictOf', 'tripVerdict',
  'fromOpenMeteo', 'aggPoints', 'mergeDaily', 'snapshotView',
  'RUB', 'NEED', 'WD', 'W_SCORE', 'ADV', 'OVER_ADV',
  'CLIMO', 'BT', 'CLIMO_META', 'BT_ORG', 'BT_LEADS',
  'SRC', 'SNAP', 'SNAP_TIME', 'SNAP_RAW', 'CACHE_KEY',
  'MDL', 'W_MDL', 'ORG', 'ORG_NAME', 'MODEL_TOTAL',
  'CONF_TXT', 'LEAD_TXT', 'CODE', 'API_BASE', 'API_GROUPS', 'LIVE_URL'
];

const header = [
  '// AUTO-GENERATED by scripts/sync-core.mjs —— 请勿手工编辑。',
  '// 源码：public/assets/snapshot-data.js + app-core.js + app-backtest.js + app-charts.js + app-runtime.js（截取到 boot() 结束）',
  ''
].join('\n');

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(
  outPath,
  header + data + '\n\n' + coreBody +
    '\nexport {\n  ' + EXPORTS.join(',\n  ') + '\n};\n',
  'utf8'
);

console.log('core:sync -> src/core/logic.js (' + (header.length + coreBody.length) + ' bytes)');
